<#
.SYNOPSIS
  Gives the Domain Whitelist Protector extension the sign-in names of the
  users who are signed in to this computer.

.DESCRIPTION
  For every signed-in domain user, the script reads the logon name, the
  e-mail address, the user principal name and the e-mail aliases from Active
  Directory and writes them to the extension's policy (protectedLogins) for
  Google Chrome and Microsoft Edge in that user's registry hive.

  The extension then warns the user when one of these names is typed into a
  field on a non-whitelisted page.

  Run this script as SYSTEM, for example as a scheduled task that starts at
  logon. Standard users cannot write below Software\Policies themselves.

  This file was generated by scripts/enterprise.js for one extension ID.

.PARAMETER SkipAliases
  Do not include additional e-mail aliases (proxyAddresses).
#>
param(
    [switch]$SkipAliases
)

$ExtensionId = '{{EXTENSION_ID}}'
$PolicyRoots = @(
    'Software\Policies\Google\Chrome',
    'Software\Policies\Microsoft\Edge'
)

function Get-SignInNames {
    param([string]$Sid)

    $names = New-Object System.Collections.Generic.List[string]

    # DOMAIN\logonname
    try {
        $account = (New-Object System.Security.Principal.SecurityIdentifier($Sid)).Translate(
            [System.Security.Principal.NTAccount]).Value
        if ($account) { $names.Add($account) }
    } catch {
        # Not resolvable; the directory lookup below may still work
    }

    $searcher = [adsisearcher]"(objectSid=$Sid)"
    foreach ($property in 'sAMAccountName', 'mail', 'userPrincipalName', 'proxyAddresses') {
        [void]$searcher.PropertiesToLoad.Add($property)
    }
    $user = $searcher.FindOne()
    if (-not $user) { return $names }

    foreach ($property in 'samaccountname', 'mail', 'userprincipalname') {
        foreach ($value in $user.Properties[$property]) {
            if ($value) { $names.Add([string]$value) }
        }
    }

    if (-not $SkipAliases) {
        foreach ($address in $user.Properties['proxyaddresses']) {
            if ($address -match '^smtp:(.+)$') { $names.Add($Matches[1]) }
        }
    }

    return $names
}

# Loaded hives of domain users (local and service accounts are skipped)
$sids = Get-ChildItem -Path 'Registry::HKEY_USERS' |
    Where-Object { $_.PSChildName -match '^S-1-5-21-[\d-]+$' } |
    ForEach-Object { $_.PSChildName }

foreach ($sid in $sids) {
    try {
        $names = @(Get-SignInNames -Sid $sid |
            ForEach-Object { $_.Trim().ToLowerInvariant() } |
            Where-Object { $_.Length -ge 3 } |
            Select-Object -Unique)
    } catch {
        Write-Warning "Could not look up ${sid}: $_"
        continue
    }
    if ($names.Count -eq 0) { continue }

    foreach ($root in $PolicyRoots) {
        $key = "Registry::HKEY_USERS\$sid\$root\3rdparty\extensions\$ExtensionId\policy\protectedLogins"
        try {
            if (Test-Path -LiteralPath $key) {
                Remove-Item -LiteralPath $key -Recurse -Force
            }
            New-Item -Path $key -Force | Out-Null

            $index = 1
            foreach ($name in $names) {
                New-ItemProperty -LiteralPath $key -Name "$index" -Value $name -PropertyType String -Force | Out-Null
                $index++
            }
        } catch {
            Write-Warning "Could not write $key : $_"
        }
    }
}
